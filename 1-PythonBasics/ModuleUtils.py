def find_cylinder_volume(radius,height):
    volume = 3.14 * (radius ** 2) * height
    return volume

def find_cuboid_volume(length,breadth,height= 3):
    '''

    :param length: length measurement
    :param breadth: breadth measurement
    :param height: height measurement
    :return:
    '''
    volume = length * breadth * height
    return  volume